def calculate_holland(answers: list) -> dict:
    """
    根据答题结果计算霍兰德类型得分。

    answers: 6个选项的列表，每个元素是 'R'/'I'/'A'/'S'/'E'/'C'
    返回: {
        'scores': {'R': 2, 'I': 1, ...},
        'top3': ['R', 'S', 'E'],
        'code': 'RSE',
        'recommended_majors': [...]
    }
    """
    scores = {t: 0 for t in "RIASEC"}
    for a in answers:
        if a in scores:
            scores[a] += 1

    sorted_types = sorted(scores.keys(), key=lambda t: scores[t], reverse=True)
    top3 = sorted_types[:3]
    code = "".join(top3)

    # 收集推荐专业（从top3类型中取，按类型权重去重）
    seen = set()
    recommended = []
    for t in top3:
        for major in HOLLAND_MAJORS[t]["majors"]:
            if major not in seen:
                seen.add(major)
                recommended.append({
                    "major": major,
                    "type": t,
                    "type_name": HOLLAND_MAJORS[t]["name"],
                })

    return {
        "scores": scores,
        "top3": [{"code": t, "name": HOLLAND_MAJORS[t]["name"], "desc": HOLLAND_MAJORS[t]["desc"], "score": scores[t]} for t in top3],
        "code": code,
        "recommended_majors": recommended,
    }
